def _lsq(idx: int):
    A = [[0.0] * 3 for _ in range(3)]
    b = [0.0] * 3
    for x, y, la, ln in ANCHORS.values():
        v = (x, y, 1.0)
        t = la if idx == 0 else ln
        for i in range(3):
            b[i] += v[i] * t
            for j in range(3):
                A[i][j] += v[i] * v[j]
    M = [A[i] + [b[i]] for i in range(3)]
    for i in range(3):
        p = max(range(i, 3), key=lambda r: abs(M[r][i]))
        M[i], M[p] = M[p], M[i]
        for r in range(3):
            if r != i:
                f = M[r][i] / M[i][i]
                for c in range(i, 4):
                    M[r][c] -= f * M[i][c]
    return [M[i][3] / M[i][i] for i in range(3)]


_CO = (_lsq(0), _lsq(1))


def map_to_latlng(x: float, y: float, k: int = 4) -> tuple[float, float]:
    """안내도 좌표 → 위경도. 전체 아핀 변환 + 가까운 기준점 k개의 잔차를 거리 가중으로 보정."""
    (a, b, c), (d, e, f) = _CO
    la, ln = a * x + b * y + c, d * x + e * y + f
    near = []
    for ax, ay, ala, aln in ANCHORS.values():
        dist = math.hypot(ax - x, ay - y)
        if dist < 1e-6:
            return ala, aln
        pla, pln = a * ax + b * ay + c, d * ax + e * ay + f
        near.append((dist, ala - pla, aln - pln))
    near.sort()
    near = near[:k]
    w = sum(1 / d2 ** 2 for d2, _, _ in near)
    la += sum((1 / d2 ** 2) * r for d2, r, _ in near) / w
    ln += sum((1 / d2 ** 2) * r for d2, _, r in near) / w
    return la, ln


