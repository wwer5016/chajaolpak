def main() -> None:
    out = ROOT / "reference" / "places.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "name", "aliases", "lat", "lng", "zone", "confidence", "source"])
        for pid, name, zone, src, xy, conf, aliases in P:
            if src == "osm":
                la, ln = xy
                source = "OpenStreetMap"
            else:
                la, ln = map_to_latlng(*xy)
                source = "올림픽공원 안내도 위치 보정"
            w.writerow([pid, name, aliases, f"{la:.6f}", f"{ln:.6f}", zone, conf, source])
    print(f"{out} — {len(P)}곳")


if __name__ == "__main__":
    main()
